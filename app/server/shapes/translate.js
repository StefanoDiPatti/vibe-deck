const SUFFIXES = [[' aperta', ' open']];
const KEYS = ['label', 'description', 'help', 'unit', 'example', 'sample', 'placeholder', 'title'];

function text(value) {
  if (Object.prototype.hasOwnProperty.call(WORDS, value)) return WORDS[value];
  for (let i = 0; i < SUFFIXES.length; i++) {
    const s = SUFFIXES[i];
    if (value.length > s[0].length && value.slice(-s[0].length) === s[0]) return text(value.slice(0, -s[0].length)) + s[1];
  }
  return value;
}

function known(value) {
  if (Object.prototype.hasOwnProperty.call(WORDS, value)) return true;
  for (let i = 0; i < SUFFIXES.length; i++) {
    const s = SUFFIXES[i];
    if (value.length > s[0].length && value.slice(-s[0].length) === s[0]) return known(value.slice(0, -s[0].length));
  }
  return false;
}

function walk(node, visit, key) {
  if (Array.isArray(node)) return node.map(function (n) { return walk(n, visit, key); });
  if (node && typeof node === 'object') {
    const out = {};
    Object.keys(node).forEach(function (k) { out[k] = walk(node[k], visit, k); });
    return out;
  }
  if (typeof node === 'string' && KEYS.indexOf(key) >= 0 && node) return visit(node);
  return node;
}

function translate(catalog, lang) {
  if (lang !== 'en') return catalog;
  return walk(catalog, text);
}

function missing(catalog) {
  const out = [];
  walk(catalog, function (v) { if (!known(v)) out.push(v); return v; });
  return out;
}

module.exports = { translate: translate, missing: missing, WORDS: WORDS };
